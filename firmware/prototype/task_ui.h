// UI 태스크 — core 0, 앱 태스크보다 낮은 우선순위.
//
// 하는 일:
//   - 5방향 스위치를 KEY_POLL_MS 마다 읽어 디바운스하고, 눌린 순간마다
//     Command{CMD_BUTTON, SRC_KEY} 를 q_cmd 에 넣는다.
//   - 앱 태스크가 ui_show() 로 넘긴 최신 화면을 LCD1602(I2C)에 그린다.
//     버튼 읽기 → LCD 그리기를 차례로 한다 — LCD 에 쓰는 동안에는 버튼을 읽지 않는다.
//
// --- 지켜야 할 것 ---
//  1. 모터·상태 모델을 건드리지 않는다. 판단은 app_task 가 q_cmd 에서 꺼내 한다(목표 7.2~7.3).
//     화면도 앱이 만든 두 줄을 받아 그대로 그릴 뿐이다(목표 7.4).
//  2. 버튼 처리는 기다리지 않는다 — delay() 도, 떼기를 기다리는 while 도 없다(목표 5.5).
//  3. LCD 가 없거나 응답하지 않아도 버튼은 계속 동작해야 한다. 응답이 없으면 그리기를 건너뛰고
//     LCD_RETRY_MS 마다 다시 찾는다(목표 7.6).
//  4. 이 태스크가 멈춰도 모터 판단과 호흡 검출은 계속 돈다(우선순위가 더 낮고 입출력만 한다).

#ifndef TASK_UI_H
#define TASK_UI_H

// 화면 큐·버튼 핀을 준비하고 UI 태스크를 core 0 에 만든다.
// q_cmd 가 만들어진 뒤, app_start() 보다 먼저 부를 것 — 앱의 첫 화면이 들어갈 자리가 있어야 한다.
void ui_start();

// LCD 에 그릴 두 줄(각 16자)을 넘긴다. app_task 가 화면이 바뀔 때 부른다.
// 한 칸짜리 큐에 덮어쓰므로 절대 기다리지 않고, UI 태스크는 항상 가장 최근 화면만 그린다.
void ui_show(const char *line0, const char *line1);

#endif  // TASK_UI_H
