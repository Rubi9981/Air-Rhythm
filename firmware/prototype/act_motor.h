// 타진 모터 — 중재 뒤의 출력 계층.
//
// 하드웨어는 BL3640N(구동드라이버 내장 BLDC) + Nidec BLC-20 컨트롤러다.
// 정류는 모터가 알아서 하므로 이 계층이 하는 일은 두 가지뿐이다:
// "얼마나 빨리 돌래"(PWM) 와 "멈춰"(BRAKE).
//
// --- 지켜야 할 것 ---
//  1. app_task(core 0)에서만 부른다. sense_task(core 1)에서 부르면 20ms 주기가 깨진다.
//  2. 매 틱 motor_set() 을 부른다 — 레벨 트리거다. 갱신이 끊기면 꺼진다.
//     app_task 가 멈추면 모터도 멈추므로, 코드 구조 자체가 워치독 역할을 한다.
//     "켜고 잊어버리는" 호출을 만들지 말 것. 신체 접촉 액추에이터에서 이 성질이 전부다.
//  3. 같은 값을 다시 쓰지 않는다. 실제 GPIO 쓰기는 값이 바뀔 때만 일어난다.
//
// --- 왜 브레이크가 따로 있는가 ---
// PWM 을 0 으로 내리는 것은 전원을 끊는 것일 뿐이라 관성으로 계속 돈다(코스팅).
// 무부하 8000RPM 에 타격 기구가 달려 있으면 관성이 상당하다. BRAKE 는 3상 코일을
// 단락시켜 역기전력으로 제동을 건다. 그래서 "정지" 는 PWM 0 과 BRAKE 둘 다여야 한다.

#ifndef ACT_MOTOR_H
#define ACT_MOTOR_H

#include <stdint.h>

// setup() 에서 한 번. 브레이크를 먼저 걸고 LEDC 를 붙이므로,
// 부팅 과정에서 모터가 튀지 않는다.
void motor_init();

// 매 틱 호출. duty 0 이면 PWM 0 + 브레이크로 정지시킨다.
// 범위 검사는 cmd_parse() 가 이미 했다 — 여기서는 받은 값을 그대로 낸다.
// 실제로 돌기 시작하는 하한(BLDC 최소 기동 듀티)은 의도적으로 클램프하지 않는다.
// 그 값을 실측하는 것이 이 단계의 목적이기 때문이다.
void motor_set(uint8_t duty);

// 자가진단 — 계측기 없이 "PWM 이 진짜 핀에서 나가는가" 를 확인한다.
//
// 두 가지를 본다:
//   1. LEDC 레지스터 되읽기 — 설정이 먹었는지 (점퍼 없이도 나온다)
//   2. 루프백 입력 샘플링 — 패드가 실제로 토글하는지 (점퍼를 이어야 나온다)
//
// 배선: PIN_MOTOR_PWM → PIN_MOTOR_PWM_LOOPBACK, PIN_MOTOR_BRAKE → PIN_MOTOR_BRAKE_LOOPBACK
//
// 주의: SELFTEST_WINDOW_MS 동안 app_task 가 블로킹된다. 그동안 motor_set() 갱신이
// 멈추므로 24V 를 넣은 상태에서는 부르지 말 것. 배선 검증 단계에서만 쓴다.
void motor_selftest();

#endif  // ACT_MOTOR_H
